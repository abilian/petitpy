//! ADR-003 L2 — frozen-tiny module table.
//!
//! Modules ship as pre-compiled `.mpy` byte buffers, baked into the
//! binary via `@embedFile`. The corresponding `.mpy` files are produced
//! by `tools/freeze_modules.py` (run by `make freeze`) and live in
//! `build-frozen/`.
//!
//! L1+L2 scope: a small frozen set (`json`, `types`) sufficient to
//! unblock the smoke test from ADR-003 §8. `os` (proposed in ADR-003
//! §D6) is deferred — the micropython-lib version of `os` is a package
//! that re-exports from the builtin `uos`, which petitpy doesn't
//! ship; a clean port needs its own stub source.
//!
//! When `MICROPY_FROZEN_TINY_ENABLED=0` (the default until `make freeze`
//! has run), the table is empty — frozen lookup always returns null and
//! sys.path filesystem search is the only external-import mechanism.

const std = @import("std");
const build_options = @import("build_options");

const Entry = struct {
    name: []const u8,
    bytes: []const u8,
};

const enabled = build_options.frozen_tiny_enabled;

// Single-blob frozen index. Under -Dfrozen-tiny=true, build.zig
// exposes two anonymous imports:
//   - `frozen_bundle` — build-frozen/frozen-bundle.bin (concatenated
//     .mpy bytes)
//   - `frozen_index`  — build-frozen/frozen-index.zig (generated by
//     tools/freeze_modules.py; comptime `table = [_]{name, bytes}{…}`
//     with each entry's bytes carved out of the bundle as a comptime
//     slice).
//
// Under -Dfrozen-tiny=false neither import exists, so the else arm
// hands back an empty table. The comptime-if is lazy: Zig only
// analyses whichever arm this build takes, so the missing @import in
// the disabled build doesn't fault.
const gen = if (enabled) @import("frozen_index") else struct {
    pub const table = [_]Entry{};
};

extern fn qstr_str(q: usize) callconv(.c) [*:0]const u8;

/// Look up frozen module bytes by qstr id.
/// Returns the byte buffer, or null if the module is not frozen.
pub fn lookup(modname_qstr: usize) ?[]const u8 {
    if (gen.table.len == 0) return null;
    const name_c = qstr_str(modname_qstr);
    var name_len: usize = 0;
    while (name_c[name_len] != 0) : (name_len += 1) {}
    const name = name_c[0..name_len];

    for (gen.table) |entry| {
        if (std.mem.eql(u8, entry.name, name)) return entry.bytes;
    }
    return null;
}

/// A frozen module is a package when some frozen entry sits under it
/// (`collections` with `collections.abc`).
pub fn isPackage(modname_qstr: usize) bool {
    const name = std.mem.span(qstr_str(modname_qstr));
    for (gen.table) |entry| {
        if (entry.name.len > name.len and entry.name[name.len] == '.' and std.mem.startsWith(u8, entry.name, name)) return true;
    }
    return false;
}

comptime {
    _ = &lookup;
}
