#!/usr/bin/env python3
"""gen_opcodes_js — render web/demos/playground/opcodes.js from vendor bc0.h.

The playground disassembles the `.mpy` that `nanopython --emit-mpy` prints, so
it needs opcode names and their operand shapes. Both come from vendor
`py/bc0.h`, the same header
`projects/pyfront/tests/a_unit/emit/test_bytecode_vendor.py` re-derives its
constants from — so a drifting header fails that suite rather than silently
producing a wrong disassembly here.

Regenerate with `make gen-opcodes`. The output carries a SHA-256 of bc0.h so
drift is visible in the diff, matching what tools/gen_grammar.py does for the
grammar tables.
"""

from __future__ import annotations

import hashlib
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
BC0 = ROOT / "vendor" / "micropython_embed" / "py" / "bc0.h"
OUT = ROOT / "web" / "demos" / "playground" / "opcodes.js"
QSTRDEFS = ROOT / "vendor" / "micropython_embed" / "genhdr" / "qstrdefs.generated.h"
OUT_QSTRS = ROOT / "web" / "demos" / "playground" / "qstrs.js"

DEFINE = re.compile(r"^#define\s+(MP_BC_\w+)\s+\(([^)]*)\)")


def _resolve(text: str, name: str) -> int:
    """A name in a `_NUM` expression is either a define in runtime0.h — and
    those chain, `MP_UNARY_OP_NUM_BYTECODE` being `(MP_UNARY_OP_NOT + 1)` —
    or an enum member whose value is its position."""
    m = re.search(rf"^#define\s+{re.escape(name)}\s+\((.+)\)", text, re.MULTILINE)
    if m:
        expr = m.group(1)
        scope = {w: _resolve(text, w) for w in re.findall(r"MP_\w+", expr)}
        return int(eval(expr, {"__builtins__": {}}, scope))
    return _enum_value(text, name)


def _enum_value(text: str, name: str) -> int:
    """Resolve an enum member of mp_unary_op_t / mp_binary_op_t by counting
    from the start of its enum: the NUM_BYTECODE markers are positions, not
    literals, so they cannot be read as defines."""
    for block in re.findall(r"typedef enum \{(.*?)\}", text, re.DOTALL):
        # Comments have to go before splitting on commas: a `// ...` line
        # above the first member otherwise swallows that member, which
        # shifts every index by one.
        clean = re.sub(r"//[^\n]*", "", block)
        members = [m.split("=")[0].strip() for m in clean.split(",")]
        members = [m for m in members if re.fullmatch(r"MP_\w+", m)]
        if name in members:
            return members.index(name)
    msg = f"cannot resolve {name} as an enum member of runtime0.h"
    raise SystemExit(msg)


def parse() -> tuple[dict[str, int], int]:
    """Resolve every MP_BC_* define, and the format bitmap.

    Values are either a literal or `BASE + offset`, so one pass in file order
    resolves them all: a base is always defined before what builds on it.
    """
    env: dict[str, int] = {}
    fmt_magic = None
    for line in BC0.read_text().splitlines():
        if "MP_BC_FORMAT(op)" in line:
            m = re.search(r"\(0x([0-9a-fA-F]+)\s*>>", line)
            if m:
                fmt_magic = int(m.group(1), 16)
            continue
        m = DEFINE.match(line.strip())
        if not m:
            continue
        name, expr = m.group(1), m.group(2).strip()
        try:
            env[name] = int(eval(expr, {"__builtins__": {}}, dict(env)))
        except (NameError, TypeError, SyntaxError, ValueError):
            continue
    if fmt_magic is None:
        msg = "MP_BC_FORMAT bitmap not found in bc0.h"
        raise SystemExit(msg)
    return env, fmt_magic


def main() -> int:
    env, fmt_magic = parse()

    # The MULTI opcodes cover a whole range; a single name per value would
    # be wrong, so they are emitted as ranges the disassembler expands.
    multis = {n: v for n, v in env.items() if n.endswith("_MULTI")}
    singles = {
        n: v
        for n, v in env.items()
        if not n.endswith("_MULTI") and not n.startswith("MP_BC_BASE_") and "FORMAT" not in n
    }

    def short(name: str) -> str:
        return name.removeprefix("MP_BC_")

    lines = [
        "// AUTO-GENERATED by tools/gen_opcodes_js.py — DO NOT EDIT.",
        "//",
        "// Source: vendor/micropython_embed/py/bc0.h",
        f"// SHA-256: {hashlib.sha256(BC0.read_bytes()).hexdigest()}",
        "//",
        "// Regenerate with `make gen-opcodes` after a vendor refresh.",
        "",
        "// Operand shape, keyed on the opcode's high nibble — vendor's",
        "// MP_BC_FORMAT(op) macro, whose bitmap is copied here verbatim.",
        f"export const FORMAT_BITMAP = 0x{fmt_magic:08x};",
        "export const FORMAT_BYTE = 0;",
        "export const FORMAT_QSTR = 1;",
        "export const FORMAT_VAR_UINT = 2;",
        "export const FORMAT_OFFSET = 3;",
        "",
        "export function formatOf(op) {",
        "  return (FORMAT_BITMAP >> (2 * (op >> 4))) & 3;",
        "}",
        "",
        "// One name per opcode value.",
        "export const OPCODES = {",
    ]
    for name, value in sorted(singles.items(), key=lambda kv: kv[1]):
        lines.append(f'  0x{value:02x}: "{short(name)}",')
    lines.append("};")
    lines.append("")
    # Each MULTI covers a range whose width is its own _NUM define — 64 for
    # small ints, 16 for fast loads, and the arity of the op tables for the
    # unary/binary ones. Assuming 16 for all of them silently mis-names every
    # LOAD_CONST_SMALL_INT above 0x7f.
    # `MP_BC_UNARY_OP_MULTI_NUM` is defined as `(MP_UNARY_OP_NOT + 1)` — an
    # enum *position*, not a literal, so it has to be counted out of
    # runtime0.h rather than read as a define.
    runtime0 = (BC0.parent / "runtime0.h").read_text()
    for line in BC0.read_text().splitlines():
        m = re.match(r"#define\s+(MP_BC_\w+_MULTI_NUM)\s+\((.+)\)", line.strip())
        if not m:
            continue
        name, expr = m.group(1), m.group(2)
        scope = {w: _resolve(runtime0, w) for w in re.findall(r"MP_\w+", expr)}
        env[name] = int(eval(expr, {"__builtins__": {}}, scope))

    lines.append("// Opcodes covering a range: `op - base` is the operand, and")
    lines.append("// `excess` is subtracted from it (small ints start negative).")
    lines.append("export const MULTI = [")
    for name, value in sorted(multis.items(), key=lambda kv: kv[1]):
        num = env.get(f"{name}_NUM", 16)
        excess = env.get(f"{name}_EXCESS", 0)
        lines.append(
            f'  {{ base: 0x{value:02x}, num: {num}, excess: {excess}, name: "{short(name)}" }},'
        )
    lines.append("];")
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(singles)} opcodes, {len(multis)} multi ranges")

    # Static qstr ids: the sequential index of each QDEF, file order. The
    # .mpy marks them with the low bit of the length prefix and carries no
    # payload, so without this table a disassembly reads `LOAD_NAME #7`
    # instead of `LOAD_NAME <module>`.
    names = re.findall(r'^QDEF[01]\(\w+,\s*\d+,\s*\d+,\s*"((?:[^"\\]|\\.)*)"\)',
                       QSTRDEFS.read_text(), re.MULTILINE)
    qlines = [
        "// AUTO-GENERATED by tools/gen_opcodes_js.py — DO NOT EDIT.",
        "//",
        "// Source: vendor/micropython_embed/genhdr/qstrdefs.generated.h",
        f"// SHA-256: {hashlib.sha256(QSTRDEFS.read_bytes()).hexdigest()}",
        "//",
        "// A qstr id is the QDEF's index in file order. The .mpy flags a",
        "// static id with the low bit of its length prefix and carries no",
        "// payload for it, so this table is what makes those readable.",
        "",
        "export const STATIC_QSTRS = [",
    ]
    for n in names:
        qlines.append(f'  "{n}",')
    qlines.append("];")
    qlines.append("")
    OUT_QSTRS.write_text("\n".join(qlines))
    print(f"wrote {OUT_QSTRS.relative_to(ROOT)}: {len(names)} static qstrs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
