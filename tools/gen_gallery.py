#!/usr/bin/env python3
"""gen_gallery — build the playground gallery from golden-programs/works/.

Prism bakes its examples into a TypeScript module. Ours are 580 programs and
608 KB of source: baking that in would nearly triple the weight of a page
whose wasm is 313 KB. So this writes a small index and copies the sources
next to it, and the playground fetches one on selection — same origin, so the
page is still a self-contained static drop.

The corpus is *measured*, not curated: `make golden` runs every program on
every arm and writes the result into a `# golden: works-on=` header. Filtering
on `nanopython-wasm` is therefore a claim the repository has already tested,
which is what makes this better than a hand-maintained manifest — and it
replaces the note at the top of examples.js: "keep in sync by hand if they
drift."
"""

from __future__ import annotations

import json
import pathlib
import re
import shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORKS = ROOT / "golden-programs" / "works"
OUT_DIR = ROOT / "web" / "gallery"
OUT_JS = ROOT / "web" / "demos" / "playground" / "gallery.js"

WORKS_ON = re.compile(r"^# golden: works-on=(.+)$", re.MULTILINE)
SOURCE = re.compile(r"^# golden: source=([^;]+)", re.MULTILINE)


def summarise(text: str) -> str:
    """The program's own one-line description: its module docstring, else its
    first real comment. Anything else would be a label we invented."""
    body = [ln for ln in text.splitlines() if not ln.startswith("# golden:")]
    for i, line in enumerate(body):
        stripped = line.strip()
        if stripped.startswith(('"""', "'''")):
            quote = stripped[:3]
            rest = stripped[3:]
            if rest.endswith(quote) and len(rest) > 3:
                return rest[:-3].strip()
            return (body[i + 1].strip() if i + 1 < len(body) else rest).strip()
        if stripped.startswith("#"):
            return stripped.lstrip("# ").strip()
        if stripped:
            break
    return ""


def main() -> int:
    entries = []
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True)

    for path in sorted(WORKS.glob("*.py")):
        text = path.read_text()
        m = WORKS_ON.search(text)
        if not m or "nanopython-wasm" not in m.group(1):
            continue
        shutil.copyfile(path, OUT_DIR / path.name)
        src = SOURCE.search(text)
        # [name, summary] pairs, not objects: 580 of them as indented JSON
        # objects came to 88 KB, which is a lot of page for a dropdown. The
        # filename is the name plus ".py", and provenance is not shown.
        del src
        entries.append([path.stem, summarise(text)[:100]])

    OUT_JS.write_text(
        "// AUTO-GENERATED by tools/gen_gallery.py — DO NOT EDIT.\n"
        "//\n"
        "// The index only. Sources live in web/gallery/ and are fetched on\n"
        "// selection: inlining them would add ~608 KB to the page.\n"
        "//\n"
        "// Each entry is [name, summary]; the file is the name plus \".py\".\n"
        "//\n"
        "// Membership is measured, not curated — every program here carries a\n"
        "// `works-on=…nanopython-wasm` header that `make golden` wrote after\n"
        "// actually running it on the wasm arm.\n"
        "\n"
        "export const GALLERY = [\n"
        + "".join(f"  {json.dumps(e)},\n" for e in entries)
        + "];\n"
    )
    print(f"wrote {OUT_JS.relative_to(ROOT)}: {len(entries)} programs")
    print(f"copied sources into {OUT_DIR.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
