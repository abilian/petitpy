#!/usr/bin/env python3
"""Emit a C shadow file holding MP_QSTR_* anchors lifted from .zig sources.

The MicroPython qstr-gen pipeline (``py/makeqstrdefs.py``) scans only
preprocessed C/C++ sources for ``MP_QSTR_<name>`` literal substrings; it
will not look at ``.zig`` files. This script lets a ``.zig`` source
declare an explicit anchor block whose lines are lifted verbatim into a
generated ``.c`` file added to ``SRC_QSTR``.

Anchor block syntax (inside a ``.zig`` file):

    // __qstr_shadow_begin__
    // #if MICROPY_PY_IO
    // MP_QSTR_FileIO
    // MP_QSTR_TextIOWrapper
    // #endif
    // __qstr_shadow_end__

Each ``// `` prefix is stripped; bare ``MP_QSTR_<name>`` identifiers
become ``__attribute__((used))`` const refs (which the qstr scanner sees
after the preprocessor runs over the shadow .c). Preprocessor directives
(lines starting with ``#``) are emitted verbatim.

Usage:
    zig_qstr_shadow.py <output.c> <zig_file> [<zig_file>...]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

BEGIN = "__qstr_shadow_begin__"
END = "__qstr_shadow_end__"

# Strip leading "// " or "//! " (doc-comment) prefix from block lines.
_LINE_RE = re.compile(r"^\s*//!?\s?(.*?)\s*$")
_QSTR_RE = re.compile(r"^MP_QSTR_[A-Za-z0-9_]+$")


def extract_blocks(zig_path: Path) -> list[str]:
    """Return the inner lines of every shadow block in ``zig_path``."""
    out: list[str] = []
    in_block = False
    for raw in zig_path.read_text().splitlines():
        if BEGIN in raw:
            in_block = True
            continue
        if END in raw:
            in_block = False
            continue
        if not in_block:
            continue
        m = _LINE_RE.match(raw)
        if not m:
            continue
        out.append(m.group(1))
    return out


def render(blocks: dict[Path, list[str]]) -> str:
    """Render the consolidated shadow .c file."""
    parts: list[str] = [
        "/* Auto-generated by tools/zig_qstr_shadow.py. Do not edit.",
        " * Anchors MP_QSTR_<name> identifiers referenced from .zig sources",
        " * so the MicroPython qstr-gen scanner (which only reads .c/.cpp)",
        " * emits the matching entries into qstrdefs.generated.h. */",
        '#include "py/obj.h"',
        '#include "py/qstr.h"',
        "",
    ]
    counter = 0
    for zig_path, lines in blocks.items():
        if not lines:
            continue
        parts.append(f"/* from {zig_path.as_posix()} */")
        for line in lines:
            if line.startswith("#"):
                parts.append(line)
            elif _QSTR_RE.match(line):
                counter += 1
                parts.append(
                    f"__attribute__((used)) static const qstr "
                    f"npy_zig_qstr_anchor_{counter} = {line};"
                )
            elif line:
                # Allow arbitrary verbatim C (e.g. MP_REGISTER_MODULE).
                parts.append(line)
        parts.append("")
    return "\n".join(parts) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print(f"usage: {argv[0]} <output.c> <zig_file>...", file=sys.stderr)
        return 2
    out_path = Path(argv[1])
    # Sort: Makefile's $(shell find) is filesystem-order-dependent. Stable
    # ordering keeps the generated .c byte-identical across rebuilds, which
    # in turn keeps qstrdefs.collected.h.hash stable so the qstr-gen step
    # doesn't regenerate downstream artifacts on no-op rebuilds.
    zig_paths = sorted(Path(p) for p in argv[2:])
    blocks: dict[Path, list[str]] = {}
    for p in zig_paths:
        lines = extract_blocks(p)
        if lines:
            blocks[p] = lines
    out_path.parent.mkdir(parents=True, exist_ok=True)
    new_text = render(blocks)
    old_text = out_path.read_text() if out_path.exists() else ""
    if new_text != old_text:
        out_path.write_text(new_text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
